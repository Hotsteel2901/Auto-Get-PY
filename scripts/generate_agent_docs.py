def deliverables() -> dict[str, str]:
    """Every generated file, as ``{relative_path: content}``."""
    files: dict[str, str] = {}

    for agent in AGENTS:
        for path in agent.config_files:
            producer = SPECIAL_FILES.get(path)
            if producer is not None:
                files[path] = producer(agent.id)
            elif path.startswith("docs/agents/"):
                files[path] = build_reference_doc(agent.id)
            elif path.endswith("SKILL.md"):
                files[path] = render_skill(agent, BASE_URL)
            else:
                files[path] = build_reference_doc(agent.id)

        # Per-agent reference doc for every agent, whether or not it lists one.
        files.setdefault(f"docs/agents/{agent.id}.md", build_reference_doc(agent.id))

    files["docs/agents/README.md"] = build_agents_index()
    files["docs/agent-manifest.json"] = build_manifest_json()
    files["docs/HERMES_SKILL.md"] = render_skill(AGENTS_BY_ID["hermes"], BASE_URL)
    return files



# ── Output validation ───────────────────────────────────────────────────────


class GeneratedFileError(ValueError):
    """A generated file would not be usable by the tool it targets."""


def validate(path: str, content: str) -> None:
    """Fail loudly if a generated file is malformed or machine-specific.

    Two bugs this catches that are otherwise invisible until a user tries the
    integration: a comment in the wrong syntax (an HTML comment inside TOML or
    YAML makes the file unparseable), and a hard-coded local checkout path that
    is wrong on every other machine.
    """
    if path.endswith(".json"):
        try:
            json.loads(content)
        except json.JSONDecodeError as exc:
            raise GeneratedFileError(f"{path} is not valid JSON: {exc}") from exc

    elif path.endswith(".toml"):
        if tomllib is None:
            return
        try:
            tomllib.loads(content)
        except Exception as exc:  # noqa: BLE001 - tomllib raises several types
            raise GeneratedFileError(f"{path} is not valid TOML: {exc}") from exc

    elif path.endswith((".yml", ".yaml")):
        if yaml is None:
            return
        try:
            yaml.safe_load(content)
        except Exception as exc:  # noqa: BLE001 - yaml raises several types
            raise GeneratedFileError(f"{path} is not valid YAML: {exc}") from exc

    # A committed file must not contain the author's checkout path.
    for needle in (str(ROOT), ROOT.as_posix()):
        if needle and needle in content:
            raise GeneratedFileError(
                f"{path} embeds the local checkout path ({needle}); "
                f"generated files must be portable")


def validate_all(files: dict[str, str]) -> None:
    problems: list[str] = []
    for path, content in sorted(files.items()):
        try:
            validate(path, content)
        except GeneratedFileError as exc:
            problems.append(str(exc))
    if problems:
        raise GeneratedFileError(
            "generated output failed validation:\n  - " + "\n  - ".join(problems))


# ── CLI ─────────────────────────────────────────────────────────────────────


def _write(path: Path, content: str, check: bool, stale: list[str]) -> None:
    relative = path.relative_to(ROOT).as_posix()
    existing = path.read_text(encoding="utf-8") if path.exists() else None
    if existing == content:
        return
    if check:
        stale.append(relative)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"{'updated' if existing is not None else 'created'}  {relative}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="Exit non-zero if any generated file is out of date")
    args = parser.parse_args()

    files = deliverables()

    try:
        validate_all(files)
    except GeneratedFileError as exc:
        print(str(exc), file=sys.stderr)
        print("\nRefusing to write invalid output.", file=sys.stderr)
        return 1

    stale: list[str] = []
    for relative, content in sorted(files.items()):
        _write(ROOT / relative, content, args.check, stale)

    if args.check:
        if stale:
            print("Out-of-date generated files:", file=sys.stderr)
            for path in stale:
                print(f"  {path}", file=sys.stderr)
            print("\nRun: python scripts/generate_agent_docs.py", file=sys.stderr)
            return 1
        print(f"All {len(files)} generated files are up to date.")
        return 0

    print(f"\n{len(files)} files generated for {len(AGENTS)} agents.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
